-- Task 2: core schema, constraints, and document type seed.
-- RLS (Task 3) and activity-log triggers (Task 4) are layered on top in later migrations.

create table public.schools (
  id uuid primary key default gen_random_uuid(),
  name text unique not null
);

create table public.document_types (
  id uuid primary key default gen_random_uuid(),
  name text unique not null,
  office text not null,
  requires_leave_dates boolean not null default false
);

create table public.profiles (
  user_id uuid primary key references auth.users on delete cascade,
  username text unique not null,
  full_name text not null,
  role text not null check (role in ('user', 'admin', 'superadmin')),
  school_id uuid references public.schools on delete restrict,
  must_change_password boolean not null default true,
  disabled boolean not null default false,
  created_at timestamptz default now(),
  constraint profiles_role_school_check check ((role = 'user') = (school_id is not null))
);

create table public.records (
  id uuid primary key default gen_random_uuid(),
  school_id uuid not null references public.schools on delete restrict,
  created_by uuid not null default auth.uid() references auth.users,
  created_by_username text not null,
  date date not null default current_date,
  name text not null,
  honorific text check (honorific in ('Mr', 'Mrs', 'Ms', 'Dr')),
  leave_type text,
  description text,
  contact text,
  title text not null,
  dts_number text not null,
  document_type_id uuid not null references public.document_types on delete restrict,
  date_from date,
  date_to date,
  excluded_date text,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  constraint records_date_range_check check (date_to is null or date_from is null or date_to >= date_from)
);

create unique index records_dts_number_key on public.records (upper(btrim(dts_number)));

create table public.activity_logs (
  id bigint generated always as identity primary key,
  at timestamptz default now(),
  user_id uuid,
  username text,
  role text,
  action text not null,
  details jsonb not null default '{}'
);

-- created_by_username is always derived from the creator's profile and is immutable,
-- so school users can see who encoded a record without reading other people's profiles.
create function public.records_set_creator()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    -- created_by is NOT NULL; let the column constraint report a missing value.
    if new.created_by is not null then
      select p.username into new.created_by_username
      from public.profiles p
      where p.user_id = new.created_by;

      if new.created_by_username is null then
        raise exception 'No profile found for record creator %', new.created_by
          using errcode = 'foreign_key_violation';
      end if;
    end if;
  else
    new.created_by := old.created_by;
    new.created_by_username := old.created_by_username;
    new.updated_at := now();
  end if;
  return new;
end;
$$;

create trigger records_set_creator
before insert or update on public.records
for each row execute function public.records_set_creator();

create function public.records_require_leave_dates()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if (new.date_from is null or new.date_to is null)
     and exists (
       select 1 from public.document_types dt
       where dt.id = new.document_type_id and dt.requires_leave_dates
     ) then
    raise exception 'Date from and Date to are required for this document type'
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger records_require_leave_dates
before insert or update on public.records
for each row execute function public.records_require_leave_dates();

